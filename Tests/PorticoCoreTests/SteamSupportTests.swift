import XCTest
@testable import PorticoCore

final class SteamSupportTests: XCTestCase {
    private var root: URL!
    private var prefix: URL!
    private var steam: URL!

    override func setUpWithError() throws {
        root = FileManager.default.temporaryDirectory.appendingPathComponent("Portico Steam Tests \(UUID().uuidString)").resolvingSymlinksInPath()
        prefix = root.appendingPathComponent("prefix")
        steam = prefix.appendingPathComponent("drive_c/Program Files (x86)/Steam")
        try file(steam.appendingPathComponent("Steam.exe"), data: Data())
    }

    override func tearDownWithError() throws {
        SteamInstallerURLProtocol.setHandler(nil)
        if let root { try? FileManager.default.removeItem(at: root) }
    }

    func testFindsWindowsSteamWithCaseInsensitiveNamesAndBothProgramFilesPaths() throws {
        XCTAssertEqual(SteamSupport.executable(in: prefix), steam.appendingPathComponent("Steam.exe"))
        try FileManager.default.removeItem(at: steam)
        let alternative = prefix.appendingPathComponent("drive_c/Program Files/STEAM/steam.EXE")
        try file(alternative, data: Data())
        XCTAssertEqual(SteamSupport.executable(in: prefix), alternative)
        XCTAssertNil(SteamSupport.executable(in: URL(string: "https://example.com")!))
    }

    func testImportsCompletedGamesAndNormalizesIDs() throws {
        try manifest("00042", id: "00042", name: "Гра \"тест\"", directory: "Test Game", flags: "4")
        try manifest("43", name: "Running game", flags: "68")
        try manifest("44", name: "Updating", flags: "6")
        try manifest("45", name: "Downloading", flags: "1048580")
        try manifest("46", name: "Uninstalled", flags: "1")
        try manifest("47", name: "Pending bytes", extra: #"""
        "BytesToDownload" "200" "BytesDownloaded" "100"
        """#)
        try manifest("48", name: "Pending staging", extra: #"""
        "BytesToStage" "200" "BytesStaged" "100"
        """#)
        try manifest("49", name: "Completed bytes", extra: #"""
        "BytesToDownload" "200" "BytesDownloaded" "200"
        "BytesToStage" "300" "BytesStaged" "300"
        """#)
        try manifest("50", id: "51", name: "Mismatched app ID")
        let games = try SteamSupport.installedGames(in: prefix)
        XCTAssertEqual(Set(games.map(\.id)), ["42", "43", "49"])
        XCTAssertEqual(games.first(where: { $0.id == "42" })?.name, "Гра \"тест\"")
        XCTAssertEqual(games.first(where: { $0.id == "42" })?.installDirectory, steam.appendingPathComponent("steamapps/common/Test Game"))
    }

    func testReadsModernAndLegacyLibrariesWithExplicitDriveMappingsAndDeduplicates() throws {
        let second = prefix.appendingPathComponent("drive_c/Steam Library")
        let external = root.appendingPathComponent("External Games")
        try FileManager.default.createDirectory(at: prefix.appendingPathComponent("dosdevices"), withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: external, withIntermediateDirectories: true)
        try FileManager.default.createSymbolicLink(at: prefix.appendingPathComponent("dosdevices/d:"), withDestinationURL: external)
        try manifest("100", name: "Main")
        try manifest("200", name: "Modern", library: second)
        try manifest("300", name: "Legacy external", library: external.appendingPathComponent("Library"))
        try manifest("100", name: "Duplicate", library: second)
        try text(steam.appendingPathComponent("steamapps/libraryfolders.vdf"), "\u{feff}" + #"""
        // Generated by Steam
        "libraryfolders"
        {
            "0" { "path" "C:\\Program Files (x86)\\Steam" "apps" { "100" "1" } }
            "1" { "path" "c:\\steam library" "label" "Games" }
            "2" "D:\\Library"
            "3" { "path" "C:\\Steam Library" }
        }
        """#)
        let games = try SteamSupport.installedGames(in: prefix)
        XCTAssertEqual(Set(games.map(\.id)), ["100", "200", "300"])
        XCTAssertEqual(games.first(where: { $0.id == "100" })?.name, "Main")
        XCTAssertEqual(games.first(where: { $0.id == "300" })?.installDirectory, external.appendingPathComponent("Library/steamapps/common/Legacy external"))
    }

    func testRejectsTraversalMissingDirectoriesAndSymlinkEscapes() throws {
        try manifest("10", name: "Valid")
        try manifest("11", name: "Traversal", directory: "../escape", createDirectory: false)
        try manifest("12", name: "Absolute", directory: "/tmp", createDirectory: false)
        try manifest("13", name: "Windows absolute", directory: "C:\\Games", createDirectory: false)
        try manifest("14", name: "Missing", createDirectory: false)
        try manifest("15", name: "Linked", createDirectory: false)
        let outside = root.appendingPathComponent("outside")
        try FileManager.default.createDirectory(at: outside, withIntermediateDirectories: true)
        try FileManager.default.createSymbolicLink(at: steam.appendingPathComponent("steamapps/common/Linked"), withDestinationURL: outside)
        XCTAssertEqual(try SteamSupport.installedGames(in: prefix).map(\.id), ["10"])
        try FileManager.default.removeItem(at: steam.appendingPathComponent("Steam.exe"))
        let externalEXE = outside.appendingPathComponent("Steam.exe")
        try file(externalEXE, data: Data())
        try FileManager.default.createSymbolicLink(at: steam.appendingPathComponent("Steam.exe"), withDestinationURL: externalEXE)
        XCTAssertNil(SteamSupport.executable(in: prefix))
    }

    func testLibraryCanUseExplicitMappedDriveRootOrTrailingBackslash() throws {
        let external = root.appendingPathComponent("mapped drive")
        try manifest("100", name: "Root library", library: external)
        try manifest("200", name: "Trailing separator", library: prefix.appendingPathComponent("drive_c/Library"))
        try FileManager.default.createDirectory(at: prefix.appendingPathComponent("dosdevices"), withIntermediateDirectories: true)
        try FileManager.default.createSymbolicLink(at: prefix.appendingPathComponent("dosdevices/d:"), withDestinationURL: external)
        try text(steam.appendingPathComponent("steamapps/libraryfolders.vdf"), #"""
        "libraryfolders" {
            "1" { "path" "D:\\" }
            "2" { "path" "C:\\Library\\" }
        }
        """#)
        XCTAssertEqual(Set(try SteamSupport.installedGames(in: prefix).map(\.id)), ["100", "200"])
    }

    func testIgnoresRootDriveMappingUNCAndLibraryTraversal() throws {
        try manifest("10", name: "Main")
        let external = root.appendingPathComponent("outside")
        try manifest("20", name: "Outside", library: external)
        try FileManager.default.createDirectory(at: prefix.appendingPathComponent("dosdevices"), withIntermediateDirectories: true)
        try FileManager.default.createSymbolicLink(at: prefix.appendingPathComponent("dosdevices/z:"), withDestinationURL: URL(fileURLWithPath: "/"))
        let externalWindowsPath = "Z:" + external.path.replacingOccurrences(of: "/", with: "\\")
        try text(steam.appendingPathComponent("steamapps/libraryfolders.vdf"), """
        "libraryfolders" {
            "1" "\(escape(externalWindowsPath))"
            "2" "C:\\\\..\\\\..\\\\outside"
            "3" "\\\\\\\\server\\\\library"
        }
        """)
        XCTAssertEqual(try SteamSupport.installedGames(in: prefix).map(\.id), ["10"])
    }

    func testMalformedManifestsDoNotHideHealthyGames() throws {
        try manifest("10", name: "Healthy")
        try text(steam.appendingPathComponent("steamapps/appmanifest_11.acf"), #"""
        "AppState" { "appid" "11" "name" "Broken
        """#)
        try manifest("12", id: "not-a-number", name: "Bad ID")
        try manifest("13", name: "Bad state", flags: "-1")
        try manifest("14", name: "Bad counts", extra: #"""
        "BytesToDownload" "not-a-number"
        """#)
        try manifest("15", name: String(repeating: "X", count: 201), directory: "Long Name")
        try manifest("16", name: "Bad\u{0001}Name", directory: "Control Name")
        try text(steam.appendingPathComponent("steamapps/libraryfolders.vdf"), "broken {")
        XCTAssertEqual(try SteamSupport.installedGames(in: prefix).map(\.id), ["10"])
    }

    func testVDFSupportsBOMCommentsBareTokensEscapesAndRejectsMalformedInput() throws {
        let parsed = try SteamVDFParser.parse("\u{feff}" + #"""
        // comment before object
        AppState {
          "Name" "Game \"quoted\" \\ slash"
          /* A block comment */ apps { 12 "50" }
          "path" "D:\Steam"
        }
        """#)
        XCTAssertEqual(parsed["appstate"]?.object?["name"], .string("Game \"quoted\" \\ slash"))
        XCTAssertEqual(parsed["appstate"]?.object?["path"], .string("D:\\Steam"))
        XCTAssertEqual(parsed["appstate"]?.object?["apps"]?.object?["12"], .string("50"))
        for invalid in ["root {", "root { key }", "}", "root { a 1 A 2 }", "/*", "key \"unfinished", String(repeating: "a { ", count: 65) + String(repeating: "}", count: 65)] {
            XCTAssertThrowsError(try SteamVDFParser.parse(invalid), invalid)
        }
    }

    func testInstallerValidationRejectsHTMLTruncatedPEAndOversizedFiles() throws {
        let installer = root.appendingPathComponent("installer.exe")
        try file(installer, data: peData())
        XCTAssertNoThrow(try SteamSupport.validateInstaller(at: installer))
        try file(installer, data: Data("<html>Steam failed</html>".utf8))
        XCTAssertThrowsError(try SteamSupport.validateInstaller(at: installer))
        var badPE = peData(); badPE[63] = 0xff
        try file(installer, data: badPE)
        XCTAssertThrowsError(try SteamSupport.validateInstaller(at: installer))
        try file(installer, data: Data(repeating: 0, count: SteamSupport.maximumInstallerBytes + 1))
        XCTAssertThrowsError(try SteamSupport.validateInstaller(at: installer))
    }

    func testOnlyOfficialHTTPSInstallerHostsAreAccepted() {
        XCTAssertNoThrow(try SteamSupport.validateInstallerURL(SteamSupport.installerURL))
        XCTAssertNoThrow(try SteamSupport.validateInstallerURL(URL(string: "https://cdn.fastly.steamstatic.com/client/installer/SteamSetup.exe")!))
        for invalid in ["http://cdn.akamai.steamstatic.com/SteamSetup.exe", "https://cdn.akamai.steamstatic.com.evil.example/installer", "https://user:pass@cdn.akamai.steamstatic.com/file", "https://cdn.akamai.steamstatic.com:444/file", "file:///tmp/SteamSetup.exe"] {
            XCTAssertThrowsError(try SteamSupport.validateInstallerURL(URL(string: invalid)!))
        }
    }

    #if !APP_STORE
    func testDownloadProducesVerifiedInstallerAndOnlyCleansOwnedDirectory() async throws {
        let data = peData()
        SteamInstallerURLProtocol.setHandler { request, client, source in
            client.urlProtocol(source, didReceive: HTTPURLResponse(url: request.url!, statusCode: 200, httpVersion: nil, headerFields: ["Content-Length": String(data.count)])!, cacheStoragePolicy: .notAllowed)
            client.urlProtocol(source, didLoad: data)
            client.urlProtocolDidFinishLoading(source)
        }
        let file = try await SteamSupport().downloadInstaller(configuration: configuration())
        XCTAssertEqual(file.lastPathComponent, "SteamSetup.exe")
        XCTAssertEqual(try Data(contentsOf: file), data)
        SteamSupport.cleanupInstaller(at: file)
        XCTAssertFalse(FileManager.default.fileExists(atPath: file.deletingLastPathComponent().path))
        let unrelated = root.appendingPathComponent("SteamSetup.exe")
        try self.file(unrelated, data: data)
        SteamSupport.cleanupInstaller(at: unrelated)
        XCTAssertTrue(FileManager.default.fileExists(atPath: unrelated.path))
    }

    func testDownloadRejectsHTTPFailuresOversizeDeclarationsAndInvalidBodies() async throws {
        let cases: [(Int, String?, Data)] = [
            (404, nil, peData()), (200, nil, Data("<html>failure</html>".utf8)),
            (200, String(SteamSupport.maximumInstallerBytes + 1), peData()), (200, "1000", peData()),
            (200, nil, Data(repeating: 0, count: SteamSupport.maximumInstallerBytes + 1))
        ]
        for (status, length, data) in cases {
            SteamInstallerURLProtocol.setHandler { request, client, source in
                client.urlProtocol(source, didReceive: HTTPURLResponse(url: request.url!, statusCode: status, httpVersion: nil, headerFields: length.map { ["Content-Length": $0] })!, cacheStoragePolicy: .notAllowed)
                client.urlProtocol(source, didLoad: data)
                client.urlProtocolDidFinishLoading(source)
            }
            do {
                let installer = try await SteamSupport().downloadInstaller(configuration: configuration())
                SteamSupport.cleanupInstaller(at: installer)
                XCTFail("Invalid response must not produce an installer: \(status), \(length ?? "unknown length")")
            } catch { XCTAssertTrue(error is SteamSupportError) }
        }
    }

    func testCancellationStopsPendingInstallerDownload() async throws {
        let started = expectation(description: "Request started")
        SteamInstallerURLProtocol.setHandler { _, _, _ in started.fulfill() }
        let config = configuration()
        let task = Task { try await SteamSupport().downloadInstaller(configuration: config) }
        await fulfillment(of: [started], timeout: 3)
        task.cancel()
        do { _ = try await task.value; XCTFail("Cancelled download must fail") }
        catch is CancellationError { }
    }
    #endif

    private func manifest(_ fileID: String, id: String? = nil, name: String, directory: String? = nil,
                          flags: String = "4", extra: String = "", library: URL? = nil, createDirectory: Bool = true) throws {
        let library = library ?? steam!
        let directory = directory ?? name
        if createDirectory {
            try FileManager.default.createDirectory(at: library.appendingPathComponent("steamapps/common").appendingPathComponent(directory), withIntermediateDirectories: true)
        }
        try text(library.appendingPathComponent("steamapps/appmanifest_\(fileID).acf"), """
        "AppState" {
            "appid" "\(id ?? fileID)"
            "name" "\(escape(name))"
            "installdir" "\(escape(directory))"
            "StateFlags" "\(flags)"
            \(extra)
        }
        """)
    }

    private func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
    }

    private func text(_ file: URL, _ text: String) throws { try self.file(file, data: Data(text.utf8)) }
    private func file(_ url: URL, data: Data) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try data.write(to: url)
    }
    private func peData() -> Data {
        var bytes = Data(repeating: 0, count: 128)
        bytes[0] = 0x4d; bytes[1] = 0x5a; bytes[60] = 64
        bytes[64] = 0x50; bytes[65] = 0x45
        return bytes
    }
    private func configuration() -> URLSessionConfiguration {
        let configuration = URLSessionConfiguration.ephemeral
        configuration.protocolClasses = [SteamInstallerURLProtocol.self]
        return configuration
    }
}

private final class SteamInstallerURLProtocol: URLProtocol {
    typealias Handler = (URLRequest, URLProtocolClient, URLProtocol) -> Void
    private static let lock = NSLock()
    private static var handler: Handler?
    static func setHandler(_ handler: Handler?) {
        lock.lock(); self.handler = handler; lock.unlock()
    }
    override class func canInit(with request: URLRequest) -> Bool { true }
    override class func canonicalRequest(for request: URLRequest) -> URLRequest { request }
    override func startLoading() {
        Self.lock.lock(); let handler = Self.handler; Self.lock.unlock()
        if let client { handler?(request, client, self) }
    }
    override func stopLoading() {}
}
